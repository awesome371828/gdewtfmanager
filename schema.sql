-- Atomic economy operations: prevents duplicate daily bonuses, overspending and partial transfers.
create or replace function public.pear_economy_action(
    p_chat_id bigint,
    p_user_id bigint,
    p_action text,
    p_target_id bigint default null,
    p_amount bigint default 0,
    p_title text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_balance bigint;
    v_target_balance bigint;
    v_last_bonus timestamptz;
    v_price bigint;
    v_now timestamptz := now();
begin
    if p_chat_id is null or p_user_id is null
       or p_action not in ('bonus', 'purchase', 'transfer') then
        return jsonb_build_object('ok', false, 'reason', 'invalid_request');
    end if;

    insert into public.bot_economy (chat_id, user_id)
    values (p_chat_id, p_user_id)
    on conflict (chat_id, user_id) do nothing;

    if p_action = 'transfer' then
        if p_target_id is null or p_target_id = p_user_id or p_amount < 1 or p_amount > 1000000 then
            return jsonb_build_object('ok', false, 'reason', 'invalid_transfer');
        end if;
        insert into public.bot_economy (chat_id, user_id)
        values (p_chat_id, p_target_id)
        on conflict (chat_id, user_id) do nothing;

        -- Lock rows in a stable order so reverse concurrent transfers do not deadlock.
        perform 1 from public.bot_economy
        where chat_id = p_chat_id and user_id in (p_user_id, p_target_id)
        order by user_id for update;

        select balance into v_balance from public.bot_economy
        where chat_id = p_chat_id and user_id = p_user_id;
        select balance into v_target_balance from public.bot_economy
        where chat_id = p_chat_id and user_id = p_target_id;

        if v_balance < p_amount then
            return jsonb_build_object('ok', false, 'reason', 'insufficient_funds', 'balance', v_balance);
        end if;

        update public.bot_economy set balance = balance - p_amount, updated_at = v_now
        where chat_id = p_chat_id and user_id = p_user_id;
        update public.bot_economy set balance = balance + p_amount, updated_at = v_now
        where chat_id = p_chat_id and user_id = p_target_id;
        return jsonb_build_object('ok', true, 'balance', v_balance - p_amount,
                                  'target_balance', v_target_balance + p_amount);
    end if;

    select balance, last_bonus into v_balance, v_last_bonus
    from public.bot_economy
    where chat_id = p_chat_id and user_id = p_user_id
    for update;

    if p_action = 'bonus' then
        if v_last_bonus is not null and v_last_bonus > v_now - interval '20 hours' then
            return jsonb_build_object('ok', false, 'reason', 'cooldown', 'balance', v_balance);
        end if;
        update public.bot_economy
        set balance = balance + 100, last_bonus = v_now, updated_at = v_now
        where chat_id = p_chat_id and user_id = p_user_id
        returning balance into v_balance;
        return jsonb_build_object('ok', true, 'balance', v_balance);
    end if;

    if p_action = 'purchase' then
        v_price := case
            when p_title in ('активный', 'титул активный') then 250
            when p_title in ('легенда', 'титул легенда') then 1000
            else null
        end;
        if v_price is null then
            return jsonb_build_object('ok', false, 'reason', 'invalid_item', 'balance', v_balance);
        end if;
        if v_balance < v_price then
            return jsonb_build_object('ok', false, 'reason', 'insufficient_funds', 'balance', v_balance);
        end if;
        update public.bot_economy
        set balance = balance - v_price, title = left(p_title, 80), updated_at = v_now
        where chat_id = p_chat_id and user_id = p_user_id
        returning balance into v_balance;
        return jsonb_build_object('ok', true, 'balance', v_balance);
    end if;

    return jsonb_build_object('ok', false, 'reason', 'invalid_request');
end;
$$;

