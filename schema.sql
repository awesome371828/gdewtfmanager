-- application code must enqueue and process events through the documented GDE.WTF API.

create table if not exists public.bot_gdewtf_project_links (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    telegram_user_id bigint not null,
    gdewtf_user_key text,
    gdewtf_pub text,
    linked_by bigint,
    linked_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (chat_id, telegram_user_id),
    check (gdewtf_user_key is null or length(gdewtf_user_key) <= 200),
    check (gdewtf_pub is null or length(gdewtf_pub) <= 80)
);

create index if not exists bot_gdewtf_project_links_user_idx
    on public.bot_gdewtf_project_links (telegram_user_id);
create index if not exists bot_gdewtf_project_links_pub_idx
    on public.bot_gdewtf_project_links (lower(gdewtf_pub))
    where gdewtf_pub is not null;

